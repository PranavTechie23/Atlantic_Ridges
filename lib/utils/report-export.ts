import type { EvidenceItem, IntelligenceReport } from "../types";

function slugify(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 48);
}

export function reportFileBaseName(report: IntelligenceReport): string {
  const date = report.date.replace(/-/g, "");
  return `PRYSM-Brief-${date}-${slugify(report.title)}`;
}

export function reportToMarkdown(report: IntelligenceReport): string {
  const lines: string[] = [];

  lines.push(`# ${report.title}`);
  lines.push("");
  lines.push(`> ${report.subtitle}`);
  lines.push("");
  lines.push("| Field | Value |");
  lines.push("| --- | --- |");
  lines.push(`| Report date | ${report.date} |`);
  lines.push(`| Surveillance period | ${report.period} |`);
  lines.push(`| Competitors monitored | ${report.competitorCount} |`);
  lines.push(`| Changes detected | ${report.changesCount} |`);
  lines.push(`| High-impact signals | ${report.highImpactCount} |`);
  lines.push(`| Avg. verification confidence | ${report.confidenceAvg}% |`);
  lines.push("");
  lines.push("---");
  lines.push("");
  lines.push("## 1. Executive Summary");
  lines.push("");
  lines.push(report.executiveSummary);
  lines.push("");
  lines.push("_All statements reference verifiable DOM snapshots in PRYSM Evidence Explorer._");
  lines.push("");

  if (report.keyChanges.length > 0) {
    lines.push("## 2. Key Changes Detected & Verified");
    lines.push("");
    report.keyChanges.forEach((kc) => {
      lines.push(`### ${kc.competitor} · ${kc.impact}`);
      lines.push("");
      lines.push(`**${kc.title}** [${kc.citationIndex}]`);
      lines.push("");
      lines.push(kc.summary);
      lines.push("");
      lines.push(`- Evidence ID: \`${kc.evidenceId}\``);
      lines.push("");
    });
  }

  if (report.competitiveMovement.length > 0) {
    lines.push("## 3. Competitive Movement & Posture Matrix");
    lines.push("");
    lines.push("| Competitor | Strategic shift | Posture | Threat impact |");
    lines.push("| --- | --- | --- | --- |");
    report.competitiveMovement.forEach((cm) => {
      lines.push(`| ${cm.competitor} | ${cm.shift} | ${cm.direction} | ${cm.impactScore}/100 |`);
    });
    lines.push("");
  }

  if (report.strategicImplications.length > 0) {
    lines.push("## 4. Strategic Implications");
    lines.push("");
    report.strategicImplications.forEach((si) => {
      const cites = si.citationIndices.map((i) => `[${i}]`).join(" ");
      lines.push(`### ${si.title} ${cites}`);
      lines.push("");
      lines.push(si.description);
      lines.push("");
    });
  }

  if (report.recommendedActions.length > 0) {
    lines.push("## 5. Recommended Actions");
    lines.push("");
    report.recommendedActions.forEach((ra) => {
      lines.push(`- **[${ra.priority}] ${ra.title}** (${ra.department}) — ${ra.description}`);
    });
    lines.push("");
  }

  const citationEntries = Object.entries(report.citations);
  if (citationEntries.length > 0) {
    lines.push("## 6. Evidence Appendix");
    lines.push("");
    citationEntries
      .sort(([a], [b]) => Number(a) - Number(b))
      .forEach(([index, cit]) => {
        lines.push(`${index}. **${cit.label}**`);
        lines.push(`   - Snippet: ${cit.snippet}`);
        lines.push(`   - Evidence ID: \`${cit.evidenceId}\``);
        lines.push("");
      });
  }

  lines.push("---");
  lines.push("");
  lines.push(`Generated by PRYSM Market Intelligence · ${new Date().toISOString()}`);
  lines.push("Classification: Internal strategy only");

  return lines.join("\n");
}

export function reportToJson(report: IntelligenceReport): string {
  return JSON.stringify(
    {
      exportedAt: new Date().toISOString(),
      generator: "PRYSM",
      report,
    },
    null,
    2
  );
}

export function downloadTextFile(content: string, filename: string, mime = "text/plain;charset=utf-8") {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.rel = "noopener";
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

export function appendLiveProvenance(
  markdown: string,
  evidence: Pick<EvidenceItem, "hashDigest" | "sourceUrl" | "observedCurrentDate" | "detectionMethod">
): string {
  return `${markdown}

## Live capture provenance

| Field | Value |
| --- | --- |
| SHA-256 digest | \`${evidence.hashDigest}\` |
| Source URL | ${evidence.sourceUrl} |
| Observation date | ${evidence.observedCurrentDate} |
| Detection method | ${evidence.detectionMethod} |
`;
}

export function downloadReportMarkdown(report: IntelligenceReport, evidence?: EvidenceItem | null) {
  let md = reportToMarkdown(report);
  if (evidence) md = appendLiveProvenance(md, evidence);
  downloadTextFile(md, `${reportFileBaseName(report)}.md`, "text/markdown;charset=utf-8");
}

export function downloadReportJson(report: IntelligenceReport) {
  downloadTextFile(reportToJson(report), `${reportFileBaseName(report)}.json`, "application/json;charset=utf-8");
}

const PRINT_BODY_CLASS = "printing-intelligence-brief";

export function attachReportPrintHandlers() {
  if (typeof window === "undefined") return () => {};

  const onBefore = () => document.body.classList.add(PRINT_BODY_CLASS);
  const onAfter = () => document.body.classList.remove(PRINT_BODY_CLASS);

  window.addEventListener("beforeprint", onBefore);
  window.addEventListener("afterprint", onAfter);

  return () => {
    window.removeEventListener("beforeprint", onBefore);
    window.removeEventListener("afterprint", onAfter);
  };
}

export function printIntelligenceBrief() {
  document.body.classList.add(PRINT_BODY_CLASS);
  window.print();
  window.setTimeout(() => document.body.classList.remove(PRINT_BODY_CLASS), 500);
}
